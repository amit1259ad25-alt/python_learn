# list is a container for storage of any type of data items .
friends = [ "Apple","Oranges",5, 456.35,False,None,"Aakash","rohan"]
print(friends) # ['Apple', 'Oranges', 5, 456.35, False, None, 'Aakash', 'rohan']

friends[1] = 56  # unlike string list are mutable .
print(friends) # ['Apple', 56, 5, 456.35, False, None, 'Aakash', 'rohan']

print(friends[3])  # list can be index just like a string (0 to lenght-1).



